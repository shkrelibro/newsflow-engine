#!/usr/bin/env python3
"""Write config/source_grades.json for scripts/build_brief.py, which cannot read YAML.

    python scripts/build_grades.py            # from config/sources/outlets.yaml and people.yaml

Grades: "trade" is every outlet listed at tier 4 in outlets.yaml, "press" every tier-3 national
business title; "premium" is the brief's own hand list plus anything marked `grade: premium` in
outlets.yaml. "people" maps a name id to its executives' names from people.yaml, so a comp headline
naming a chief executive is flagged for review. Re-run after editing either file and commit the
result; the brief falls back to its built-in lists when the JSON is missing.
"""
from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import urlsplit

import yaml

ROOT = Path(__file__).resolve().parents[1]


def host(url: str) -> str:
    h = urlsplit(url).netloc.lower()
    return h[4:] if h.startswith("www.") else h


def main() -> int:
    outlets = yaml.safe_load((ROOT / "config/sources/outlets.yaml").read_text(encoding="utf-8")) or {}
    grades: dict[str, set[str]] = {"premium": set(), "trade": set(), "press": set()}
    for _, lst in (outlets.get("countries") or {}).items():
        for o in lst or []:
            h = host(o.get("homepage") or "")
            if not h:
                continue
            if o.get("grade") == "premium":
                grades["premium"].add(h)
            elif int(o.get("tier", 3)) == 4:
                grades["trade"].add(h)
            elif int(o.get("tier", 3)) == 3:
                grades["press"].add(h)
    people: dict[str, list[str]] = {}
    praw = yaml.safe_load((ROOT / "config/sources/people.yaml").read_text(encoding="utf-8")) or {}
    for nid, spec in (praw.get("names") or {}).items():
        names = []
        for p in (spec or {}).get("people", []) or []:
            text = p.get("text") if isinstance(p, dict) else str(p)
            if text and text not in names:
                names.append(text)
        if names:
            people[str(nid)] = names
    out = {"_note": "generated by scripts/build_grades.py from config/sources/outlets.yaml and people.yaml",
           **{k: sorted(v) for k, v in grades.items()}, "people": people}
    (ROOT / "config/source_grades.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"source_grades.json: {', '.join(f'{k} {len(v)}' for k, v in grades.items())}, people for {len(people)} names")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
